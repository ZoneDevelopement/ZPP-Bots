    public enum Type {
        INTEGER,
        DECIMAL,
        BOOLEAN
    }

    private final String key;
    private final Type type;
    private final BigDecimal min;
    private final BigDecimal max;

    TuningKey(String key, Type type, double min, double max) {
        this.key = key;
        this.type = type;
        this.min = BigDecimal.valueOf(min);
        this.max = BigDecimal.valueOf(max);
    }

    public String key() {
        return key;
    }

    public Type type() {
        return type;
    }

    public BigDecimal min() {
        return min;
    }

    public BigDecimal max() {
        return max;
    }

    public Object checked(Object value) {
        try {
            if (type == Type.BOOLEAN) {
                if (value instanceof Boolean) return value;
                throw new ArithmeticException();
            }
            if (!(value instanceof BigDecimal number)) throw new ArithmeticException();
            if (number.compareTo(min) < 0 || number.compareTo(max) > 0) throw new ArithmeticException();
            if (type == Type.INTEGER) return number.intValueExact();
            return number;
        } catch (RuntimeException e) {
            throw new IllegalArgumentException(key);
        }
    }
